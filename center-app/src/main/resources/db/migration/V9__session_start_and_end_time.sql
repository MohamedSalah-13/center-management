-- وقت بداية الحصة ووقت نهايتها: ما جرى فعلاً على الساعة.
--
-- كان الجدول يحمل session_date وحده، أي اليوم الذي تُنسب إليه الحصة - وهو
-- تاريخ يُختار في الشاشة وقد يكون يوماً مضى - ولا شيء فيه يقول متى فُتحت
-- الحصة ومتى أُغلقت. started_at يُكتب لحظة الفتح، و ended_at لحظة الإغلاق.
--
-- الفرق مأخوذ من target/schema-mysql.sql الذي يولّده SchemaScriptGenerator من
-- الكيانات، لا مكتوباً يدوياً: ddl-auto=validate يرفض بدء التشغيل عند أي اختلاف.
--
-- datetime لا time: الحصة تُترك مفتوحة إلى صباح اليوم التالي أحياناً - وهي
-- الحالة التي يقوم لها تنبيه SESSION_LEFT_OPEN - فساعةٌ بلا يومها تجعل حصة
-- انتهت في التاسعة صباحاً تبدو أقصر من الصفر.
--
-- والعمودان يقبلان NULL عن قصد، ولا تُملأ بهما الصفوف القائمة: الحصص المسجَّلة
-- قبل هذه الإضافة لم يُقَس وقتها، و session_date وقتاً للفتح تخمينٌ يُقرأ بعد
-- سنة على أنه قياس. الخانة الفارغة تقول "غير معلوم"، وهو الصدق.
--
-- ملاحظة: ADD COLUMN IF NOT EXISTS لهجة MariaDB وتفشل على MySQL، فلا تُستعمل.
-- =====================================================================

alter table sessions
    add column started_at datetime(6),
    add column ended_at datetime(6);
