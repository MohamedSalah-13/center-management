package com.codejava.center.platform;

/**
 * حال اشتراك المؤسسة، وثلاثتها تختلف في نتيجةٍ واحدة: أتعمل لها المهام التلقائية؟
 *
 * <p>ليست حالاتٍ إدارية بل قراراتٍ تشغيلية. مؤسسةٌ متوقفة الاشتراك تبقى بياناتها
 * كاملة ويبقى الدخول إليها قراراً منفصلاً، لكن مجدوِل النسخ ومحرّك التنبيهات لا
 * يعملان لها: خادمٌ يرسل رسائل إلى أولياء أمور سنترٍ توقّف عن الدفع منذ شهرين يفعل
 * ذلك باسم ذلك السنتر.</p>
 *
 * <p>ولا {@code getDisplayName} هنا: النواة تقرّر والحافة تتكلّم، والصياغة تخصّ
 * شاشةَ إدارة المنصة يوم تُكتب.</p>
 */
public enum TenantStatus {

    /** اشتراك قائم: تُخدَم كاملةً */
    ACTIVE,

    /** اشتراك متوقف: البيانات كما هي، ولا مهام تلقائية تعمل باسمها */
    SUSPENDED,

    /** انتهت: لا تُخدَم ولا تُرحَّل قاعدتها، وتبقى محفوظة حتى تنقضي مدّة الحفظ */
    CLOSED;

    /** أتعمل لها المهام التلقائية - النسخ الاحتياطي وفحص التنبيهات؟ */
    public boolean isServed() {
        return this == ACTIVE;
    }

    /**
     * أتُطبَّق عليها ترحيلات المخطط عند الإقلاع؟
     *
     * <p>الموقوفة نعم والمغلقة لا: اشتراكٌ يعود بعد شهرين يجب أن يجد قاعدته موافقة
     * لبرنامج اليوم، ومؤسسةٌ انتهت لا تُفتح مرة أخرى فترحيلُها تغييرٌ في بيانات لن
     * تُقرأ إلا في نزاع.</p>
     */
    public boolean isMigrated() {
        return this != CLOSED;
    }
}
