package com.codejava.center.util;

import com.codejava.center.domain.enums.Currency;

/**
 * بأيّ عملة يُعرض المال في هذه اللحظة.
 *
 * <p>والجوابان مختلفان اختلافاً يستحق واجهة. على سطح المكتب الجهاز يخدم سنتراً واحداً،
 * فالعملة قيمةٌ واحدة تُقرأ من {@code CenterSettings} عند الإقلاع وتُحدَّث بعد كل حفظ.
 * وعلى خادمٍ يخدم مئة سنتر، "عملة السنتر" جملةٌ بلا معنى ما لم يُذكر أيُّ سنتر: الجواب
 * يأتي من {@code TenantContext} ويُحفظ مؤقتاً <b>لكل مؤسسة</b>، ويسقط من الذاكرة حين
 * تحفظ تلك المؤسسة وحدها إعداداتها.</p>
 *
 * <p>وهي <b>دالة تُستدعى</b> لا حقلٌ يُقرأ مرة، للسبب نفسه: حقلٌ واحد في الـ JVM يجعل
 * آخرَ سنترٍ حفظ إعداداته يذيّل مبالغَ السناتر الأخرى برمز عملته.</p>
 *
 * <h2>لماذا هي هنا لا في النواة</h2>
 *
 * <p>لأنها تعيد {@link Currency} - نوعٌ من طبقة الأعمال، عمودٌ في {@code center_settings}
 * واسمٌ مترجَم من حزمة النصوص - والنواة لا تعرف عملات. نفس سبب بقاء
 * {@code MessagingLinkPreferences} بجوار مستهلكها بدل النواة، وعكس {@code LocaleProvider}
 * الذي يعيد {@code Locale} من الـ JDK.</p>
 *
 * <h2>الذاكرة المؤقتة ليست ترفاً</h2>
 *
 * <p>{@code formatWithCurrency} يُستدعى في كل خلية جدول وكل سطر كشف، فتنفيذٌ يستعلم من
 * القاعدة داخل {@link #current()} يعني استعلاماً لكل صفّ على الشاشة.</p>
 *
 * @see MoneyUtils#install(CurrencyProvider)
 */
@FunctionalInterface
public interface CurrencyProvider {

    /**
     * @return عملة السنتر الحالي، أو {@code null} إن لم تُختر عملة بعد - قاعدةٌ مُرقّاة
     *         من نسخة أقدم لا تحمل قيمة في العمود. و{@link MoneyUtils#currency()} هو
     *         الموضع الوحيد الذي يحلّ ذلك إلى {@link Currency#DEFAULT}، كي لا يكون على
     *         كل تنفيذ أن يتذكّره - وهو بعينه الخلل الذي وقع في مدّة حفظ النسخ حين
     *         اختلفت الشاشة والخدمة في معنى "غير مضبوط".
     */
    Currency current();
}
