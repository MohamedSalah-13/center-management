package com.codejava.center.domain.enums;

import com.codejava.center.util.I18n;

/**
 * عملة السنتر.
 *
 * <p>كانت العملة نصّاً واحداً في حزمة الترجمة ({@code app.currency}) يقول "ج.م" بالعربية
 * و"EGP" بالإنجليزية، أي أن البرنامج كان يفترض أن كل من يستعمله في مصر. صارت اختياراً
 * يملكه السنتر في {@code CenterSettings}، يُقرأ في {@link com.codejava.center.util.MoneyUtils}
 * ويُذيَّل به كل مبلغ يُعرض أو يُطبع أو يُرسل إلى ولي أمر.</p>
 *
 * <h2>عملة واحدة للسنتر، لا عملة لكل حركة</h2>
 *
 * <p>الأرصدة والمستحقات وكشوف المعلمين كلها جمع وطرح لأعمدة {@code DECIMAL(12,2)}؛ جمعُ
 * مبالغ بعملات مختلفة يحتاج سعر صرف مؤرَّخاً لكل حركة، وهو ما لا يحتاجه سنتر يبيع حصصه
 * بعملة بلده. لذلك العملة هنا <b>وحدة العرض لكل النظام</b>، لا خاصية للحركة.</p>
 *
 * <p>ومن ذلك يتبع تحذير الشاشة عند التبديل: تغيير العملة <b>لا يحوّل مبلغاً واحداً</b>
 * مما هو محفوظ - خمسمئة جنيه تصير خمسمئة ريال بالرقم نفسه. التحويل قرار محاسبي لا
 * يصحّ أن يقع كأثر جانبي لاختيار من قائمة.</p>
 *
 * <h2>إضافة عملة</h2>
 *
 * <p>ثابت جديد هنا + مفتاحان في حزمتَي النصوص ({@code currency.<NAME>} للاسم المعروض
 * و{@code currency.<NAME>.symbol} للرمز الذي يُذيَّل به المبلغ). لا ترحيل Flyway: العمود
 * {@code varchar} لا {@code enum} تحديداً حتى لا تحتاج كل عملة تُضاف إلى ملف ترحيل خاص
 * بها - نفس السبب الذي منع زرع صفوف قواعد التنبيهات في الترحيل.
 * و{@code MessageBundleTest} يُسقط البناء عند نسيان أي من المفتاحين.</p>
 *
 * <p>الرمز في الإنجليزية هو رمز الأيزو (USD) لا العلامة ($): علامة الدولار وحدها تخصّ
 * أكثر من عشرين دولة، وإيصال مطبوع لا يقول أي دولار هو لا يفيد قارئه بعد سنة.</p>
 *
 * <p>الخانات العشرية تبقى اثنتين لكل العملات - وهو ما تفرضه أعمدة {@code DECIMAL(12,2)}
 * لا اختيار العرض - راجع {@link com.codejava.center.util.MoneyUtils}.</p>
 */
public enum Currency {

    EGP,
    SAR,
    USD,
    EUR;

    /**
     * العملة حين لا تُختار: الجنيه المصري.
     *
     * <p>ليست تفضيلاً بل حفاظاً على السلوك: قاعدة بيانات مُرقّاة من نسخة أقدم لا تحمل
     * قيمة في العمود، وكل مبالغها كُتبت بالجنيه. أي افتراض آخر يعيد تسمية أموال قائمة.</p>
     */
    public static final Currency DEFAULT = EGP;

    /** الاسم الكامل كما يظهر في قائمة الاختيار - المفتاح {@code currency.<NAME>} */
    public String getDisplayName() {
        return I18n.get("currency." + name());
    }

    /** الرمز الذي يُذيَّل به المبلغ - المفتاح {@code currency.<NAME>.symbol} */
    public String getSymbol() {
        return I18n.get("currency." + name() + ".symbol");
    }
}
