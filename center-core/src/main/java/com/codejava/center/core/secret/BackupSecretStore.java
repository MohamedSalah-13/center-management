package com.codejava.center.core.secret;

/**
 * من أين تأتي كلمة مرور تشفير النسخ الاحتياطية.
 *
 * <p>الجواب مختلف على الطرفين اختلافاً جوهرياً، ولذلك هو واجهة لا قراءة مباشرة: في
 * Desktop سرٌّ معمّى في تفضيلات الجهاز ({@code java.util.prefs})، وفي الخادم صفٌّ مشفَّر
 * أو خزنة أسرار. القاعدة المشتركة وحدها هي التي لا تتغير: <b>السرّ لا يُحفظ داخل ما
 * يحميه</b> — كلمة مرورٍ في قاعدة البيانات تخرج داخل كل نسخة منها، وتضيع بضياعها، وهو
 * الحدث الذي وُجدت النسخ من أجله أصلاً.</p>
 *
 * <p>الحفظ ليس هنا: من يكتب السرّ هو الشاشة التي تعرفه، وطبقة الأعمال لا تحتاج إلا
 * قراءته لحظة أخذ النسخة.</p>
 */
public interface BackupSecretStore {

    /** هل تُشفَّر النسخ التي يأخذها هذا الطرف */
    boolean encryptionEnabled();

    /**
     * كلمة المرور، أو {@code null} إن لم تُضبط.
     *
     * <p>تعود {@code char[]} لا {@code String}: النص الثابت يبقى في ذاكرة الـ JVM حتى
     * يجمعه الكانس، والمصفوفة يمحوها المستدعي فور استعمالها — <b>وهو مسؤول عن محوها</b>.</p>
     */
    char[] passphrase();
}
