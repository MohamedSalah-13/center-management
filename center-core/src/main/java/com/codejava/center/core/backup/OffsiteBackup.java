package com.codejava.center.core.backup;

/**
 * إلى أين تخرج النسخة من هذا الجهاز، وبأي رمز.
 *
 * <p>النسخةُ اليوم تُكتب حيث يقول {@code backupPath}، والملفُّ يبقى حيث كُتب. على جهازٍ
 * في سنتر ذلك قرارُ صاحبه: يوجّه المسار إلى فلاشة أو إلى قرص الشبكة، فتخرج النسخةُ من
 * الجهاز بفعله هو. <b>وعلى خادمٍ يخدم خمسين سنتراً ينقلب المعنى</b> - الملفُّ المشفَّر
 * يجلس على القرص نفسه الذي يحمل قواعدَ الخمسين، فعطبُ ذلك القرص يأخذ القواعدَ
 * والنسخَ معاً. ونسخةٌ احتياطية تموت مع ما تحميه ليست نسخةً احتياطية.</p>
 *
 * <h2>لا مفتاحَ تشغيلٍ بجوار العنوان</h2>
 *
 * <p>الضبطُ موجود حين يوجد عنوانٌ ورمز، لا حين يُرفع علَمٌ ثالث. وهو الدرسُ نفسه
 * المكتوب في {@code EnvironmentSecrets.encryptionEnabled}: مفتاحان يصنعان حالةً رابعة
 * بلا معنى - "مفعَّل وبلا وجهة" - وهي التي تُسقط الرفعَ كل ليلة عند من ظنّ أنه ضبط
 * الاثنين.</p>
 *
 * <p>وعنوانٌ بلا رمز ليس "غيرَ مضبوط" بل <b>مضبوطٌ ومكسور</b>: أحدُهم كتب العنوان
 * قاصداً، فالسكوتُ عنه يترك سنتراً يظنّ نسخَه خارج الخادم وهي لم تبرحه. يُحاوَل ويُردّ
 * بسببه، ويُقال.</p>
 *
 * <p>ولا شيء من هذا يُخزَّن في قاعدة السنتر: الرمزُ يفتح المستودعَ الذي تعيش فيه كلُّ
 * نسخه، فحفظُه داخل ما يحميه يشحنه مع كل نسخة - وهي نفسُ حجّة كلمة مرور التشفير في
 * {@link com.codejava.center.core.secret.BackupSecretStore}.</p>
 */
public interface OffsiteBackup {

    /**
     * عنوان المستودع، أو {@code null} إن لم يُطلب إخراجُ النسخ أصلاً.
     *
     * <p>يُرفع الملفُّ إليه بـ {@code PUT} ويُحمل الرمزُ في ترويسة. والوصفُ بهذا القدر
     * من العموم مقصود: السناتر تشتري التخزين من مزوّدين محليين يسمّي كلٌّ منهم حقولَه
     * باسمه، وذلك فرقٌ في سطر إعدادٍ لا في البرنامج - نفسُ ما قيل في بوابة الرسائل
     * العامة.</p>
     */
    String endpoint();

    /**
     * رمزُ الدخول إلى المستودع.
     *
     * <p>{@code char[]} لا {@code String}، كعقد {@code BackupSecretStore}: النصُّ يبقى
     * في الذاكرة حتى يرفعه جامعُ المهملات، والمصفوفة تُمحى بعد الاستعمال.</p>
     */
    char[] token();

    /**
     * مجلَّدُ هذا السنتر داخل المستودع، أو {@code null} فيُرفع إلى جذره.
     *
     * <p>على خادمٍ هو اسمُ مخطَّط المؤسسة: مستودعٌ واحد تجتمع فيه نسخُ الخمسين، ونسخةٌ
     * تُكتب فوق نسخة جارتها لأن الاسمين تشابها عطبٌ لا يُكتشف إلا يوم الاستعادة.</p>
     */
    String folder();
}
