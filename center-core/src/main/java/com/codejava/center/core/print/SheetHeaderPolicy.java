package com.codejava.center.core.print;

/**
 * هل تحمل الورقة المملوءة ترويسة السنتر — الشعار والاسم والهاتف — في رأسها.
 *
 * <p>سؤالٌ يُطرح لحظة <b>التعبئة</b> لا لحظة التسليم: الشرط مكتوب على فرقة الترويسة في
 * ملف التصميم، فالورقة تُملأ بها أو بدونها ولا سبيل لنزعها بعد ذلك. ولهذا بقي هذا وحده
 * في النواة بينما انتقل ما سواه — أي طابعة، وهل تُرسل الورقة إليها رأساً — إلى جهة
 * التسليم في Desktop.</p>
 *
 * <p>وهو تفضيل جهاز لا سياسة سنتر رغم أن ما يحمله بيانات السنتر: السبب الذي يُطفئه أن
 * الورق المحمّل في <b>هذه</b> الطابعة مطبوعة عليه الترويسة سلفاً، وتلك خاصية درج ورق لا
 * قرارٌ يخصّ السنتر كله. Desktop يجيب من تفضيلات الجهاز؛ والخادم من إعدادات الفرع الذي
 * يطلب الكشف، أو بـ {@code true} دائماً لورقة تُقرأ على شاشة لا على ورق مطبوع سلفاً.</p>
 */
public interface SheetHeaderPolicy {

    /** الافتراضي في Desktop هو {@code true}: ورقةٌ بلا اسم مُصدِرها لا يُعرف بعد شهر من أين خرجت */
    boolean printsCenterHeader();
}
