package com.codejava.center.core.ui;

/**
 * أين يُنفَّذ ما يمسّ شاشةً تشاهد الآن.
 *
 * <p>طبقة الأعمال تقرأ من قاعدة البيانات على خيط خلفي — نبضةَ مجدوِل، أو خيطَ حدث — ثم
 * تسلّم ما قرأته إلى من يعرضه. والتسليم لا يقع حيث وقعت القراءة: في JavaFX لا يُمسّ عقدٌ
 * إلا من خيط التطبيق وإلا فالسلوك غير معرَّف، وعلى خادم SSE يُكتب إلى المُصدِر الذي فتحه
 * الطلب. الفرق بين الطرفين هو هذا السطر وحده، فهو الذي صار واجهة.</p>
 *
 * <p>كان {@code AlertFeed} يحمل {@code Platform::runLater} في حقل داخله، وهو استدعاء
 * يتطلب أدوات JavaFX مُقلعة — فلا هو يعمل على خادم بلا نافذة، ولا في خادم البناء. Desktop
 * يركّب خيط JavaFX؛ والخادم لاحقاً يركّب ما يناسب SSE.</p>
 *
 * <p><b>ولا يُفترض شيء عن التوقيت:</b> قد يُنفَّذ الآن على نفس الخيط، وقد يُؤجَّل إلى
 * دورة لاحقة. من يسلّم يقرأ حالته <i>داخل</i> المهمة لا خارجها، لأن الشاشة قد تكون
 * انسحبت بين الجدولة والتنفيذ.</p>
 */
public interface UiDispatcher {

    void dispatch(Runnable task);
}
