package com.codejava.center.core.print;

/**
 * وجهة الطباعة كما يقرّرها الطرف الذي يطبع فعلاً.
 *
 * <p>الطابعة ليست سياسة سنتر بل خاصية جهاز: اسمُ طابعةٍ لا معنى له على جهاز آخر، وورقُ
 * الرول في درج طابعةٍ بعينها. لذلك كانت طبقة الأعمال تقرأ هذه القيم من
 * {@code java.util.prefs} مباشرةً — ومعها كانت تجرّ {@code javafx.print} إلى خدمةٍ
 * يُفترض أن تعمل على خادم بلا شاشة ولا طابعة واحدة.</p>
 *
 * <p>Desktop يركّب تفضيلات الجهاز كما هي؛ والخادم لاحقاً يركّب ما يناسبه: لا طابعة أصلاً
 * ({@code null} فتُصدَّر الورقة PDF)، أو طابعة الفرع المختارة في إعداداته.</p>
 */
public interface PrintTargetResolver {

    /**
     * اسم الطابعة المختارة لهذا النوع من المستندات.
     *
     * <p>النوع لا يُهمَل: إرسال إيصال إلى طابعة التقارير يعني ورقة A4 كاملة لأجل سبعة
     * أسطر، والعكس كشفٌ يخرج من رول 80mm مقصوصاً من طرفيه.</p>
     *
     * @return الاسم، أو {@code null} أي "اترك الأمر لطابعة النظام الافتراضية"
     */
    String printerName(DocumentKind kind);

    /**
     * هل تُرسَل كشوف جاسبر إلى الطابعة رأساً بدل فتحها PDF.
     *
     * <p>الافتراضي في Desktop هو {@code false}: الطباعة المباشرة تخرج ورقة بلا سؤال،
     * وترقيةٌ تشغّلها من تلقاء نفسها تعني ورقاً يخرج من طابعة لم يطلبه أحد.</p>
     */
    boolean printsSheetsDirectly();

    /**
     * هل تُطبع ترويسة السنتر — الشعار والاسم والهاتف — في رأس الكشوف.
     *
     * <p>سببُ إطفائها أن الورق المحمّل في <b>هذه</b> الطابعة مطبوعة عليه الترويسة سلفاً،
     * وتلك خاصية درج ورقٍ لا قرارٌ يخصّ السنتر كله.</p>
     */
    boolean printsCenterHeader();
}
