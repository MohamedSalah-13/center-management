package com.codejava.center.core.backup;

/**
 * أيّ قاعدة بيانات تُنسخ، وبأي أدوات.
 *
 * <p>النسخة الاحتياطية عملية خارجية: تستدعي {@code mysqldump} و{@code mysql} وتمرّر لهما
 * مضيفاً ومنفذاً واسمَ قاعدة واعتماداً. وكل واحدة من هذه الخمس يعرفها طرفٌ ولا يعرفها
 * الآخر:</p>
 *
 * <ul>
 *   <li><b>Desktop</b> يشتقّها من رابط JDBC الذي يعمل عليه البرنامج نفسه — وهو الجواب
 *       الصحيح هناك بالضبط: النسخة يجب أن تكون من القاعدة التي يكتب فيها الكاشير الآن،
 *       لا من قاعدة أخرى تحمل الاسم نفسه على المنفذ الافتراضي.</li>
 *   <li><b>الخادم</b> يشتقّها من صفّ المؤسسة: schema هذا السنتر وحده، لا القاعدة التي
 *       يتصل بها الخادم لخدمة مئة سنتر.</li>
 * </ul>
 *
 * <p>و<b>مسار الأدوات</b> معها لأنه من الجنس نفسه: مثبِّت MySQL على ويندوز لا يضيفها إلى
 * {@code PATH}، فيبحث Desktop عنها في مجلدات التركيب المعروفة ويحفظ ما وجد لكل جهاز —
 * وهو فحصُ قرصٍ لا معنى له على خادم Linux تكون فيه الأداة في {@code PATH} أو لا تكون.</p>
 *
 * <p>الدوال تُستدعى لحظة أخذ النسخة لا عند الإقلاع: البحث عن الأدوات يقرأ القرص، وفعله
 * عند بناء الـ bean يعني تأخيراً في كل إقلاع لأجل ميزة قد لا تُستعمل اليوم.</p>
 */
public interface BackupTarget {

    /** المضيف الذي تُطلب منه النسخة */
    String host();

    /** المنفذ، نصّاً لأنه يُمرَّر وسيطاً لأداة سطر أوامر */
    String port();

    /** اسم قاعدة البيانات — أو schema المؤسسة على خادم متعدّد المستأجرين */
    String database();

    String username();

    /** كلمة مرور قاعدة البيانات، أو {@code null} إن لم تكن هناك واحدة */
    String password();

    /**
     * مجلد {@code mysqldump}/{@code mysql}، أو {@code null} إن كانت الأدوات في
     * {@code PATH} فتُستدعى بأسمائها المجرّدة.
     */
    String toolDirectory();

    /**
     * المجلد الذي يجب أن تبقى النسخ والاستعادة داخله، أو {@code null} لبلا حدّ.
     *
     * <p>سطح المكتب يجيب {@code null}، وهو الصواب هناك: قرصُ صاحب السنتر قرصُه، ومن
     * يجلس أمام الجهاز يكتب حيث شاء بلا برنامجنا - وحدُّ المسار يمنع أشيع ما يُطلب
     * فعلاً، وهو مجلدٌ على فلاشة أو على شبكة السنتر.</p>
     *
     * <p>وخادمٌ يجيب بمجلد المؤسسة. هناك ينقلب المعنى: نصٌّ في شاشة أحدهم يصير مسار
     * كتابةٍ على قرص الخادم - dump كامل بكل بيانات سنترٍ في مجلدٍ يقرؤه غيره، أو ملفُ
     * استعادةٍ يُقرأ من مجلد سنترٍ آخر فتُكتب بياناته فوق بياناتك.</p>
     *
     * <p>الافتراضي {@code null} حتى لا يضطرّ كل تنفيذ قائم إلى سطر، ولأن "بلا حدّ" هو
     * السلوك الذي كان - فالإضافة لا تغيّر جهازاً قائماً.</p>
     */
    default java.nio.file.Path backupRoot() {
        return null;
    }
}
