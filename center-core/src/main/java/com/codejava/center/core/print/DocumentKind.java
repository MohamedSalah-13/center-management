package com.codejava.center.core.print;

/**
 * نوع المستند المطبوع، وهو ما يحدّد الطابعة والورق وأسلوب تقسيم الصفحات.
 *
 * <p>التفريق ليس تجميلياً: الجهاز الواحد في السنتر قد يكون موصولاً بطابعة حرارية للإيصالات
 * وطابعة A4 للتقارير في الوقت نفسه، فلكل نوع طابعته ومقاس ورقه.</p>
 *
 * <p>مكانه النواة لا الواجهة لأنه يَعبر الحدّ: من يملأ الورقة يعلّمها بنوعها، ومن يسلّمها
 * — على جهازٍ آخر أو في وحدة أخرى — يقرأ العلامة ليختار الطابعة. ولهذا لا يحمل
 * {@code getDisplayName()} كبقية الثوابت المعروضة: ترجمة الاسم شأن الواجهة، والنواة لا
 * تعرف لغةً ولا حزمة رسائل.</p>
 */
public enum DocumentKind {

    /** تقرير على ورق مقطوع (A4 غالباً): يُقسَّم على صفحات، وتتكرر ترويسته، وتُرقَّم صفحاته */
    REPORT,

    /** إيصال على رول متصل: صفحة واحدة مهما طالت، بلا ترقيم ولا ترويسة مكرَّرة */
    RECEIPT
}
