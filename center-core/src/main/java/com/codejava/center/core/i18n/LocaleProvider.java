package com.codejava.center.core.i18n;

import java.util.Locale;

/**
 * بأيّ لغة يتكلّم البرنامج في هذه اللحظة.
 *
 * <p>والجوابان مختلفان اختلافاً يستحق واجهة. على سطح المكتب اللغة خاصيةُ <b>الجهاز</b>:
 * إنسانٌ واحد أمام شاشة واحدة اختارها من قائمة، ومحفوظةٌ في سجلّ ويندوز لأن شاشة الدخول
 * تحتاجها قبل أن يكون هناك مستخدم أو جلسة. وعلى خادمٍ هي خاصيةُ <b>الطلب</b>: ترويسة
 * {@code Accept-Language} أو تفضيلُ صاحب الحساب، ويقرأ اثنان الصفحة نفسها في اللحظة
 * نفسها بلغتين.</p>
 *
 * <p>ولهذا هي <b>دالة تُستدعى</b> لا حقلٌ يُقرأ مرة: قيمةٌ تُلتقط عند الإقلاع تكون على
 * الخادم لغةَ أوّلِ من طلب، تُجاب بها بقية الطلبات.</p>
 *
 * <p>ما تعيده يجب ألّا يكون {@code null}: من لم يُعلن لغةً يأخذ لغة البرنامج الافتراضية،
 * والحافة هي من يعرف أيّها — النواة لا تعرف لغة.</p>
 */
@FunctionalInterface
public interface LocaleProvider {

    Locale current();
}
