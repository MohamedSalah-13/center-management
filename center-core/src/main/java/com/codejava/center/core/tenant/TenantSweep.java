package com.codejava.center.core.tenant;

import java.util.function.Consumer;

/**
 * تنفيذُ عملٍ دوريّ مرةً لكل مؤسسة يخدمها هذا البرنامج، كلٌّ داخل سياقها.
 *
 * <p><b>ولا توجد دالة تُعدّد المؤسسات وحدها.</b> "أعطني القائمة" ثم "اعمل داخل واحدة"
 * خطوتان، ومن ينسى الثانية يقرأ بيانات المؤسسة الأولى ويكتبها باسم الثانية - تسرّبٌ
 * لا يُسقط شيئاً ولا يظهر في سجل. كلتا الدالتين هنا تضبط السياق حول العمل، فلا سبيل
 * إلى الحصول على معرّف مؤسسة بلا أن تكون داخلها.</p>
 *
 * <p>على سطح المكتب المؤسسة واحدة، فالتنفيذ سطرٌ واحد يستدعي العمل كما هو - بلا حلقة
 * ولا سياق يُضبط ويُعاد. وعلى خادمٍ حلقةٌ على المؤسسات <b>الخادمة</b> وحدها: مؤسسةٌ
 * موقوفة الاشتراك أو مغلقة لا تُنسخ ولا تُفحص تنبيهاتها.</p>
 *
 * <p><b>ومن يخدم أكثر من واحدة يعزل الفشل.</b> نسخةٌ ليلية تتوقف عند السنتر الثالث
 * تترك سبعةً وتسعين بلا نسخة، وأحدٌ لا يعلم. التنفيذ الذي يخدم واحدة لا يعزل شيئاً:
 * معالجةُ الخطأ هناك للمستدعي كما كانت - وهو ما يبقي تنبيه {@code BACKUP_FAILED}
 * يعمل على الجهاز كما كان قبل هذا كله.</p>
 */
public interface TenantSweep {

    /** لكل مؤسسة تُخدَم، مرةً واحدة، داخل سياقها */
    void sweep(Consumer<TenantId> work);

    /**
     * لمؤسسةٍ بعينها، داخل سياقها.
     *
     * <p>لازمةٌ لأن المجدوِل يفصل بين لحظة الجدولة ولحظة التنفيذ: الموعد يُحسب اليوم
     * والعمل يقع الليلة على خيطٍ من مجمّع لا يعرف لمن يعمل. ولا تفتح الباب الذي
     * أُغلق أعلاه - المؤسسة مذكورة في الاستدعاء، والسياق مضمونٌ حولها.</p>
     */
    void within(TenantId tenant, Runnable work);
}
