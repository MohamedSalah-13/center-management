package com.codejava.center.domain.enums;

import com.codejava.center.util.I18n;

/**
 * تصنيف التنبيه بحسب موضوعه، لا بحسب من يصله.
 *
 * <p>الفصل بين التصنيف و{@link AlertAudience} مقصود: تذكير المتأخرات موضوعه مالي ووجهته
 * ولي الأمر، وتنبيه المستحقات غير المصروفة موضوعه مالي أيضاً ووجهته المدير. لو كان
 * المحور واحداً لَاضطرّ كل نوع أن يختار بين أن يوصَف بموضوعه أو بوجهته، وضاع أحدهما.</p>
 *
 * <p>التصنيف هو ما تصفّي به الشاشة، ولذلك هو أيضاً ما يحدّد ترتيب القواعد فيها.</p>
 */
public enum AlertCategory {

    /** ما يخصّ الطالب وولي أمره: الغياب والانقطاع */
    STUDENTS,

    /** المال: المتأخرات والأرصدة ومستحقات المعلمين */
    FINANCE,

    /** تشغيل السنتر يوماً بيوم: حصص وقاعات ومجموعات */
    OPERATIONS,

    /** سلامة النظام نفسه: النسخ الاحتياطي، الأمان، قناة الإرسال */
    SYSTEM;

    /** الاسم المعروض بلغة الواجهة - المفتاح {@code alertCategory.<NAME>} */
    public String getDisplayName() {
        return I18n.get("alertCategory." + name());
    }
}
