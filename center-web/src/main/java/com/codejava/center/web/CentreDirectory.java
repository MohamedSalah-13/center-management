package com.codejava.center.web;

import com.codejava.center.core.tenant.TenantId;

/**
 * أيّ سنترٍ يقصد من يحاول الدخول.
 *
 * <p>هذا السؤال يسبق المصادقة ولا يمكن أن يليها، وهو ما يجعل الدخول على منصة مختلفاً
 * عن الدخول على جهاز: جدول {@code users} داخل قاعدة المؤسسة، فلا سبيل إلى البحث عن
 * اسم المستخدم قبل معرفة أيّ قاعدة تُسأل. ولذلك نموذج الدخول يحمل ثلاثة حقول لا
 * اثنين.</p>
 *
 * <p>وعلى تركيبٍ يخدم سنتراً واحداً - جهازاً كان أو خادماً لسنتر واحد - لا سؤال أصلاً:
 * القاعدة واحدة، والحقل الثالث يُتجاهل إن كُتب.</p>
 */
public interface CentreDirectory {

    /**
     * @param slug اسم السنتر كما يكتبه صاحبه، وقد يكون فارغاً على تركيب بسنتر واحد
     * @throws IllegalArgumentException إن لم يكن سنتراً يُخدَم
     */
    TenantId resolve(String slug);
}
