package com.codejava.center.service.dto;

/**
 * ما جرى فعلاً عند تمرير الكارنيه.
 *
 * <p>ثلاث حالات لا اثنتان: البوابة الواحدة صارت تسجّل الدخول والانصراف معاً، ولو بقي
 * الجواب {@code boolean} لظهر الانصراف الناجح بلون الدخول الناجح نفسه - فيمرّر الموظف
 * الكارنيه ظاناً أنه سجّل دخول الطالب وقد سجّل خروجه.</p>
 */
public enum AttendanceOutcome {

    /** دخول جديد: سُجّل الحضور وخُصمت رسوم الحصة */
    CHECKED_IN,

    /** انصراف: كُتب وقت الخروج، ولا حركة مالية - الخصم وقع عند الدخول */
    CHECKED_OUT,

    /** مرفوض: باركود مجهول، أو حساب موقوف، أو رصيد لا يكفي، أو تمريرة مكرّرة */
    REJECTED
}
