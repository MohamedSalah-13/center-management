package com.codejava.center.service.dto;

import com.codejava.center.util.I18n;

/**
 * حال الطالب في صفٍّ من كشف الحضور والانصراف.
 *
 * <p>خانة {@code time_out} الفارغة لا تعني شيئاً واحداً، ولذلك ثلاث حالات لا اثنتان:
 * فارغةٌ وحصتها مفتوحة تعني أن الطالب بالداخل الآن، وفارغةٌ وقد أُغلقت الحصة تعني أن
 * انصرافه لم يُسجَّل - غادر ولم يمرّر كارنيهه. الخلط بينهما يجعل كشف الأسبوع الماضي
 * يقول إن نصف السنتر ما زالوا في القاعات.</p>
 */
public enum AttendanceState {

    /** بالداخل الآن: لا وقت انصراف، والحصة ما زالت مفتوحة */
    INSIDE,

    /** انصرف: وقت الخروج مسجَّل */
    LEFT,

    /** أُغلقت الحصة ولم يُسجَّل انصرافه؛ مدة مكوثه غير معلومة */
    NOT_RECORDED;

    public String getDisplayName() {
        return I18n.get("attendanceState." + name());
    }
}
