package com.codejava.center.domain.enums;

/**
 * كم مرة يُسأل فاحصُ النوع.
 *
 * <p>الفحص اليومي في موعد يختاره السنتر يكفي لكل ما يُقاس بالأيام: غياب، متأخرات،
 * انقطاع، تأخّر نسخة احتياطية. وهو <b>عديم الفائدة تماماً</b> لِما يُقاس بالدقائق -
 * "حصة تبدأ بعد ربع ساعة" تصل في الثامنة صباحاً بلا معنى، والحصة تبدأ الرابعة عصراً.</p>
 *
 * <p>ولذلك يعلن كل نوع وتيرته، ويشغّل {@code AlertScheduler} نبضتين: واحدة يومية
 * بموعد وتعويض، وواحدة كل بضع دقائق لا تعويض لها - تذكيرٌ بموعد فات لا يُعوَّض بعد
 * ساعتين، هو خبرٌ لا تنبيه.</p>
 *
 * <p>ليست قيمة تُخزَّن ولا تُعرض للمستخدم: هي صفة النوع في الكود، والشاشة تعرض الحدود
 * التي يضبطها المستخدم لا وتيرة فحصه.</p>
 */
public enum AlertCadence {

    /** مع الفحص اليومي المجدول */
    DAILY,

    /** مع النبضة القصيرة، لأن دقّته بالدقائق */
    FREQUENT
}
