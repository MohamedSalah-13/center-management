-- فهرس المسجَّلين حالياً: (is_active, name).
--
-- شاشة تسجيل الطلاب كانت تقرأ الجدول كاملاً في كل فتح. وجدول الطلاب تراكمي
-- بطبعه: حذفُ من له حضور أو حركة مالية تمنعه المفاتيح الأجنبية - وهو صواب،
-- إذ محو صفوفه معه يغيّر أرقام أيام أُقفلت خزينتها - فيبقى كل من مرّ بالسنتر
-- منذ افتتاحه في الجدول. أي أن ما تقرأه الشاشة ينمو بعمر السنتر بينما ما
-- يعني الموظف أمام الجهاز هو طلاب العام الجاري.
--
-- المخرج هو العمود is_active الموجود أصلاً - وبوابة الحضور تفحصه منذ البداية،
-- فالطالب الموقوف يُردّ عليها - ولم يكن في الواجهة ما يضبطه. صار "الأرشفة":
-- الشاشة تقرأ المسجَّلين وحدهم، وخانةٌ تُظهر المؤرشفين عند الحاجة.
--
-- العمودان معاً في فهرس واحد لا is_active وحده: قيمتان لا غير، فالفهرس
-- المفرد عليه لا يُقلّل شيئاً يُذكر وMySQL تتجاهله. مع name يخدم الفهرسُ
-- الشرطَ والترتيبَ في مرور واحد.
--
-- الفرق مأخوذ من target/schema-mysql.sql الذي يولّده SchemaScriptGenerator من
-- الكيانات، لا مكتوباً يدوياً: ddl-auto=validate يرفض بدء التشغيل عند أي اختلاف.
--
-- لا صفّ يتغيّر هنا: كل الطلاب القائمين is_active = 1، وهو الصحيح - لم يكن
-- في البرنامج ما يؤرشف أحداً، فأرشفة أيٍّ منهم آلياً تخمينٌ بلا سند.
-- =====================================================================

create index idx_student_active on students (is_active, name);
