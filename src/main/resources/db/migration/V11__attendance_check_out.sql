-- وقت انصراف الطالب: النصف الثاني من الحضور.
--
-- كان الجدول يحمل time_in وحده، فكل ما يعرفه النظام أن الطالب دخل. أما "من
-- بالداخل الآن" و"كم مكث" فلم تكونا معلومتين ضائعتين، بل معلومتين لم تُسجَّلا
-- قطّ - ولذلك كانت شاشة الحضور تُفرغ جدولها في كل تنقّل ولا شيء يملؤه من
-- قاعدة البيانات.
--
-- الفرق مأخوذ من target/schema-mysql.sql الذي يولّده SchemaScriptGenerator من
-- الكيانات، لا مكتوباً يدوياً: ddl-auto=validate يرفض بدء التشغيل عند أي اختلاف.
--
-- العمود يقبل NULL، وNULL هي المعنى نفسه: "لم يُسجَّل انصراف". ولا تُملأ به
-- الصفوف القائمة ولا حتى عند إغلاق الحصة: ختمُ وقت الإغلاق على من لم يمرّر
-- كارنيهه عند خروجه يجعل من غادر في السابعة يبدو كأنه بقي إلى العاشرة، ويُقرأ
-- الرقم بعد شهر على أنه واقع. الخانة الفارغة تقول "غير معلوم"، وهو الصدق -
-- وهو اختيار started_at/ended_at في V9 نفسه.
--
-- datetime لا time لسبب V9 نفسه: حصةٌ تمتدّ إلى ما بعد منتصف الليل تجعل ساعةً
-- بلا يومها تقول إن الطالب انصرف قبل أن يدخل.
--
-- ولا فهرس جديد: الاستعلام يُصفّي بتاريخ الحصة - وجدول sessions صغير، ينمو
-- بعدد المجموعات في اليوم لا بعدد الطلاب - ثم يصل إلى attendances عبر
-- session_id وله فهرس المفتاح الأجنبي أصلاً.
--
-- ملاحظة: ADD COLUMN IF NOT EXISTS لهجة MariaDB وتفشل على MySQL، فلا تُستعمل.
-- =====================================================================

alter table attendances
    add column time_out datetime(6);
