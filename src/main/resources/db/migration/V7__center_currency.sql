-- =====================================================================
-- عملة السنتر: اختيار يملكه السنتر بدل نصّ ثابت في حزمة الترجمة.
--
-- كانت العملة مفتاحاً واحداً (app.currency) يقول "ج.م" بالعربية و"EGP" بالإنجليزية،
-- أي أن البرنامج كان يفترض أن كل من يستعمله في مصر. صارت عموداً هنا تعدّله شاشة
-- الإعدادات، ويُذيَّل به كل مبلغ يُعرض أو يُطبع أو يُرسل إلى ولي أمر.
--
-- الفرق مأخوذ من target/schema-mysql.sql الذي يولّده SchemaScriptGenerator من
-- الكيانات، لا مكتوباً يدوياً: ddl-auto=validate يرفض بدء التشغيل عند أي اختلاف.
--
-- العمود يقبل NULL عن قصد: قاعدة بيانات قائمة لن تحمل قيمة، وعملة غائبة تعني
-- Currency.DEFAULT أي الجنيه المصري - السلوك نفسه قبل الترقية بالضبط. ولا تُكتب
-- 'EGP' في الصفوف القائمة هنا: ذلك يسجّل اختياراً لم يقم به صاحب السنتر.
--
-- ولماذا varchar لا enum كبقية الثوابت في هذا الجدول: عملة تُضاف في نسخة لاحقة
-- (درهم، دينار) يجب أن تكون ثابتاً في Currency ومفتاحَي ترجمة فقط. لو كان العمود
-- enum لَاحتاجت كل عملة ملف ترحيل خاصاً بها، ونسيانه يجعل الاختيار من الشاشة يفشل
-- عند الحفظ - نفس السبب الذي منع زرع صفوف قواعد التنبيهات في V5.
--
-- ما لا يفعله هذا الترحيل: تحويل مبلغ واحد. تغيير العملة يغيّر ما يُقرأ به الرقم
-- لا الرقم نفسه، والتحويل قرار محاسبي لا أثر جانبي لترقية.
--
-- ملاحظة: ADD COLUMN IF NOT EXISTS لهجة MariaDB وتفشل على MySQL، فلا تُستعمل.
-- =====================================================================

alter table center_settings
    add column currency varchar(10);
