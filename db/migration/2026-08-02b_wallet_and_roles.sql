START TRANSACTION;

-- ---------------------------------------------------------------------
-- 1) عمود تاريخ بداية دفتر الحسابات
--    Hibernate سينشئه تلقائياً بـ ddl-auto=update، لكن نضيفه هنا صراحةً
--    حتى نتمكن من ضبط قيمته في نفس العملية.
-- ---------------------------------------------------------------------
ALTER TABLE center_settings
    ADD COLUMN IF NOT EXISTS ledger_start_date DATE NULL;

-- ---------------------------------------------------------------------
-- 2) تثبيت بداية دفتر الحسابات على تاريخ اليوم
--
--    مهم جداً: الدفعات المسجَّلة قبل تطبيق نظام الرصيد ليست لها قيود
--    خصم (SESSION_CHARGE) مقابلة. لو احتُسبت لظهر كل طالب دائناً بمبلغ
--    وهمي كبير ودخل البوابة مجاناً لأسابيع.
--
--    بتثبيت التاريخ على اليوم يبدأ كل الطلاب برصيد صفر، وتُحصَّل الاشتراكات
--    من جديد عبر شاشة الخزينة. هذا هو الخيار الذي اتُّفق عليه.
-- ---------------------------------------------------------------------
INSERT INTO center_settings (id, ledger_start_date, auto_backup_enabled)
VALUES (1, CURDATE(), FALSE)
ON DUPLICATE KEY UPDATE ledger_start_date = CURDATE();

-- ---------------------------------------------------------------------
-- 3) التحقق من صلاحيات المستخدمين
--    العمود يبقى VARCHAR وتبقى القيم "ADMIN"/"SECRETARY" كما هي،
--    لأن الـ enum الجديد يُخزَّن بـ EnumType.STRING بنفس النصوص.
--    هذا الاستعلام يكشف أي قيمة مخزَّنة لا تطابق الـ enum وستُسبب
--    فشلاً عند قراءة المستخدم.
-- ---------------------------------------------------------------------
SELECT id, username, role AS invalid_role
FROM users
WHERE role NOT IN ('ADMIN', 'SECRETARY');
-- إن ظهرت أي صفوف أعلاه، صحّحها يدوياً قبل تشغيل النسخة الجديدة، مثال:
--   UPDATE users SET role = 'SECRETARY' WHERE id = <id>;

COMMIT;

